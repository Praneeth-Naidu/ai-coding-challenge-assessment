import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { loadConfig } from './config.js';
import {
  buildScenarioPrompt,
  generateScenarioSpec,
  generateWithValidationRetries
} from './generate.js';
import { createChat } from './llm.js';
import { buildParsePrompt, parseCriteria, type Scenario } from './parse.js';
import { tempSpecPath, validateFile } from './validate.js';

const args = new Set(process.argv.slice(2));
const config = loadConfig(process.env, !args.has('--check') && !args.has('--dry-run'));
const chat = config.model ? createChat(config) : async () => { throw new Error('LLM_MODEL is required for generation.'); };
const examplePath = join(config.projectRoot, 'e2e/tests/hand-written/enquiry.spec.ts');

function header(scenario: Scenario): string {
  return `/**\n * Generated by testgen; model: ${config.model}; date: ${new Date().toISOString().slice(0, 10)}\n * Scenario: ${scenario.id}\n * REVIEW BEFORE TRUSTING\n */\n`;
}

async function checkGenerated(): Promise<boolean> {
  const names = (await readdir(config.outDir).catch(() => [] as string[])).filter((name) => name.endsWith('.spec.ts'));
  if (names.length === 0) {
    process.stdout.write('No generated spec files found.\n');
    return true;
  }
  let allOk = true;
  for (const name of names) {
    const path = join(config.outDir, name);
    const scenarioId = name.replace(/\.spec\.ts$/, '');
const result = await validateFile(
  path,
  config.contractPath,
  config.projectRoot,
  undefined,
  scenarioId
);
    process.stdout.write(`${result.ok ? 'PASS' : 'FAIL'} ${name}${result.errors.length ? `\n${result.errors.join('\n')}` : ''}\n`);
    allOk = allOk && result.ok;
  }
  return allOk;
}


async function removeStaleSpecs(scenarios: Scenario[]): Promise<void> {
  const expectedNames = new Set(
    scenarios.map((scenario) => `${scenario.id}.spec.ts`)
  );

  const existingNames = await readdir(config.outDir);

  const staleNames = existingNames.filter(
    (name) => name.endsWith('.spec.ts') && !expectedNames.has(name)
  );

  for (const name of staleNames) {
    await rm(join(config.outDir, name), { force: true });
    process.stdout.write(`REMOVED stale spec ${name}\n`);
  }
}

async function generateOne(scenario: Scenario): Promise<{ attempts: number; ok: boolean; errors: string[] }> {
  const candidate = tempSpecPath(config.outDir, scenario.id);
  const result = await generateWithValidationRetries(config.maxRetries, async (correction) => {
    const source = await generateScenarioSpec(scenario, { contractPath: config.contractPath, examplePath }, chat, correction);
    await writeFile(candidate, `${header(scenario)}\n${source}\n`, 'utf8');
const validation = await validateFile(
  candidate,
  config.contractPath,
  config.projectRoot,
  scenario.then.length,
  scenario.id
);    return { value: source, errors: validation.errors };
  });
  const outputPath = join(config.outDir, `${scenario.id}.spec.ts`);
  if (result.ok) {
    await writeFile(outputPath, `${header(scenario)}\n${result.value}\n`, 'utf8');
  } else {
    // Do not leave a previous passing draft in place when this run fails for the same scenario.
    await rm(outputPath, { force: true });
  }
  await rm(candidate, { force: true });
  return { attempts: result.attempts, ok: result.ok, errors: result.errors };
}

async function main(): Promise<void> {
  if (args.has('--check')) {
    process.exitCode = await checkGenerated() ? 0 : 1;
    return;
  }

  const criteria = await readFile(config.criteriaPath, 'utf8');
  if (args.has('--dry-run')) {
  process.stdout.write('STAGE 1 PROMPT\n\n');
  process.stdout.write(buildParsePrompt(criteria));

  const scenarios = await parseCriteria(criteria, async (messages) => {
    // Dry-run must not call the LLM.
    // Use representative scenarios to inspect Stage 2 templates.
    return JSON.stringify({
      scenarios: [
        {
          id: 'home-page-featured-products',
          title: 'Home page displays featured products',
          given: ['I have chosen 5 products to be top rated'],
          when: ['I am viewing the home page'],
          then: ['I see those 5 featured products']
        },
        {
          id: 'enquiry-receive-email',
          title: 'Enquiry form submits successfully',
          given: ['I am viewing a product'],
          when: ['I submit the enquiry form'],
          then: [
            'The sales inbox will receive an email',
            'The customer will see a Thank you message'
          ]
        }
      ]
    });
  }, 1);


  for (const scenario of scenarios) {
    process.stdout.write(`\n\nSTAGE 2 PROMPT — ${scenario.id}\n\n`);
    process.stdout.write(
      await buildScenarioPrompt(scenario, {
        contractPath: config.contractPath,
        examplePath
      })
    );
  }

  return;
}

  await mkdir(config.outDir, { recursive: true });
  const scenarios = await parseCriteria(criteria, chat, config.maxRetries);
  await removeStaleSpecs(scenarios);

  const report: string[] = ['# Generated test report', '', `Model: \`${config.model}\``, `Generated: ${new Date().toISOString()}`, '', '| Scenario | Attempts | Validation |', '|---|---:|---|'];
  let allOk = true;
  for (const scenario of scenarios) {
    const result = await generateOne(scenario);
    report.push(`| ${scenario.id} — ${scenario.title.replace(/\|/g, '\\|')} | ${result.attempts} | ${result.ok ? 'PASS' : 'FAIL'} |`);
    if (!result.ok) {
      allOk = false;
      report.push('', `### ${scenario.id} errors`, '', ...result.errors.map((error) => `- ${error.replace(/\n/g, ' ')}`), '');
    }
  }
  await writeFile(join(config.outDir, 'REPORT.md'), `${report.join('\n')}\n`, 'utf8');
  process.stdout.write(`${report.join('\n')}\n`);
  if (!allOk) process.exitCode = 1;
}

main().catch((error: unknown) => {
  process.stderr.write(`${error instanceof Error ? error.stack ?? error.message : 'Unknown testgen failure'}\n`);
  process.exitCode = 1;
});
